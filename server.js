// Helper: extract JSON from text
function extractJSON(text) {
  // Clean common issues
  const cleaned = text.replace(/[\x00-\x1f]/g, (c) => c === '\n' || c === '\r' || c === '\t' ? c : '');

  try {
    return JSON.parse(cleaned);
  } catch {}

  // Try markdown code block
  const jsonMatch = cleaned.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (jsonMatch) {
    try { return JSON.parse(jsonMatch[1].trim()); } catch {}
  }

  // Try finding JSON object
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start !== -1 && end !== -1 && end > start) {
    try { return JSON.parse(cleaned.substring(start, end + 1)); } catch {}

    // Try fixing truncated JSON by closing brackets
    let jsonStr = cleaned.substring(start, end + 1);
    const openBraces = (jsonStr.match(/{/g) || []).length;
    const closeBraces = (jsonStr.match(/}/g) || []).length;
    if (openBraces > closeBraces) {
      jsonStr += "}".repeat(openBraces - closeBraces);
      try { return JSON.parse(jsonStr); } catch {}
    }
  }

  throw new Error("Could not parse response. Raw: " + cleaned.substring(0, 300));
}

// Helper: compress image if needed
async function compressImage(buffer, mimetype) {
  if (buffer.length > 4 * 1024 * 1024) {
    const compressed = await sharp(buffer)
      .resize(1600, 1600, { fit: "inside", withoutEnlargement: true })
      .jpeg({ quality: 80 })
      .toBuffer();
    return { buffer: compressed, mediaType: "image/jpeg" };
  }
  return { buffer, mediaType: mimetype };
}

